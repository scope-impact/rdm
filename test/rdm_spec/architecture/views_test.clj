(ns rdm-spec.architecture.views-test
  (:require [babashka.fs :as fs]
            [clojure.string :as str]
            [clojure.test :refer [deftest is]]
            [rdm-spec.architecture.model :as model]
            [rdm-spec.architecture.model-test :refer [small]]
            [rdm-spec.architecture.views :as views]))

(deftest diagram-ids-are-model-ids-written-plainly
  (is (= "project__init" (views/mermaid-id :project/init)))
  (is (= "rdm_spec_system" (views/mermaid-id :rdm-spec-system))))

(defn- source [k]
  (views/mermaid small (first (filter #(= k (:key %)) (:views small))) "abc" "m.edn"))

(deftest the-first-line-records-the-model-hash
  (is (str/starts-with? (source "ctx") "%% model-sha256: abc; generated by rdm-spec views from m.edn, view \"ctx\"")))

(deftest a-context-view-in-mermaid
  (is (= ["C4Context" "title Context"
          "System(s, \"S\", \"A system\")"
          "Person(p, \"P\", \"A person\")"
          "System_Ext(x, \"X\", \"An external system\")"
          "Rel(p, s, \"Uses\")" "Rel(s, x, \"Calls\")" "Rel(x, s, \"Feeds\")"]
         (rest (remove str/blank? (str/split-lines (source "ctx")))))))

(deftest a-component-view-in-mermaid
  (is (= ["C4Component" "title One"
          "Boundary(boundary__one, \"one\", \"bounded context\") {"
          "  Component(one__a, \"A\", \"\", \"a\")"
          "  Component(one__b, \"B\", \"\", \"b\")"
          "}"
          "Component_Ext(two__c, \"C\", \"\", \"c\")"
          "Component_Ext(kernel__k, \"K\", \"kernel\", \"k\")"
          "Rel(one__a, one__b, \"Asks\")" "Rel(one__b, two__c, \"Publishes E\")" "Rel(one__a, kernel__k, \"Runs on\")"]
         (rest (remove str/blank? (str/split-lines (source "one")))))))

(deftest a-container-view-draws-stores-as-databases
  (let [s (source "cont")]
    (is (str/includes? s "System_Boundary(boundary__s, \"S\") {\n  Container(app, \"App\", \"t\", \"Runs\")\n  ContainerDb(db, \"DB\", \"files\", \"Stores\")\n}"))))

(deftest quotes-are-escaped
  (let [m (assoc-in small [:people 0 :description] "Says \"hi\"")]
    (is (str/includes? (views/mermaid m (first (:views m)) "h" "m.edn") "Person(p, \"P\", \"Says #quot;hi#quot;\")"))))

(deftest freshness-names-every-stale-or-missing-output
  (let [h (model/model-hash small)
        lines {"v/ctx.mmd" (str "%% model-sha256: " h) "v/ctx.svg" (str "<!-- model-sha256: " h " -->")
               "v/cont.mmd" (str "%% model-sha256: " (apply str (repeat 64 "0"))) "v/cont.svg" "<svg>"
               "v/one.mmd" (str "%% model-sha256: " h)}
        fs (views/freshness-findings small h "v" lines)]
    (is (= [["v/cont.mmd" "view-stale"] ["v/cont.svg" "view-stale"] ["v/one.svg" "view-missing"]
            ["v/dyn.mmd" "view-missing"] ["v/dyn.svg" "view-missing"]]
           (map (juxt :file :rule) fs)))
    (is (str/includes? (:message (first fs)) "\"cont\""))))

(deftest views-are-generated-rendered-and-then-fresh
  (when (fs/which views/renderer)
    (let [dir (str (fs/create-temp-dir))
          req (fn [] {:root dir :config {:model "m.edn" :views-dir "v"} :state (atom {})})]
      (spit (str (fs/file dir "m.edn")) (pr-str small))
      (let [{:keys [result findings]} (views/views (req))]
        (is (= [] findings))
        (is (= 8 (count (get-in result [:views :written])))))
      (let [svg (slurp (str (fs/file dir "v/ctx.svg")))]
        (is (str/starts-with? svg (str "<!-- model-sha256: " (model/model-hash small))))
        (is (str/includes? svg "<svg")))
      (is (= [] (:findings (views/check (req)))))
      (spit (str (fs/file dir "m.edn")) (str ";; reformatted\n" (pr-str small) "\n\n"))
      (is (= [] (:findings (views/check (req)))))
      (spit (str (fs/file dir "m.edn")) (pr-str (assoc-in small [:system :name] "T")))
      (is (= 8 (count (:findings (views/check (req)))))))))

(deftest a-model-that-cannot-be-read-writes-no-view
  (let [dir (str (fs/create-temp-dir))]
    (spit (str (fs/file dir "m.edn")) "{:system")
    (let [{:keys [findings]} (views/views {:root dir :config {:model "m.edn" :views-dir "v"} :state (atom {})})]
      (is (= ["model-edn"] (map :rule findings)))
      (is (not (fs/exists? (fs/file dir "v")))))))
