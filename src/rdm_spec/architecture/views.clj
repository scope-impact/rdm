(ns rdm-spec.architecture.views
  "Generates every view of the model as diagram source and renders it beside
  it, each recording the model hash on its first line; a view recording
  another hash is stale (dhf/spec/04-model-the-architecture/views.feature)."
  (:require [babashka.fs :as fs]
            [clojure.string :as str]
            [rdm-spec.architecture.model :as model]
            [rdm-spec.kernel.project :as project]))

(defn mid [id] (-> (str (when (namespace id) (str (namespace id) "__")) (name id)) (str/replace #"[^A-Za-z0-9_]" "_")))

(defn q [s] (str "\"" (str/replace (str s) "\"" "'") "\""))

(defn- shape-of [el ext?]
  (case (:el el)
    :person (if ext? "Person_Ext" "Person")
    :system (if ext? "System_Ext" "System")
    :external "System_Ext"
    :container (if (= :stores (:kind el)) (if ext? "ContainerDb_Ext" "ContainerDb") (if ext? "Container_Ext" "Container"))
    :component (if ext? "Component_Ext" "Component")
    :context "System_Boundary"
    "System"))

(defn- el-line [el ext?]
  (let [s (shape-of el ext?)]
    (case (:el el)
      :container (str s "(" (mid (:id el)) ", " (q (:name el)) ", " (q (:technology el)) ", " (q (:description el)) ")")
      :component (str s "(" (mid (:id el)) ", " (q (:name el)) ", \"\", " (q (:description el)) ")")
      (str s "(" (mid (:id el)) ", " (q (:name el)) ", " (q (:description el)) ")"))))

(defn header [h model-file view] (str "model-sha256: " h "; generated by rdm-spec views from " model-file ", view " (q (:key view)) "; do not edit"))

(defn mermaid
  "A view's diagram source, its first line recording the model hash."
  [m view h model-file]
  (let [{:keys [elements rels inside]} (model/view-elements m view)
        kind (case (:level view) :context "C4Context" :container "C4Container" :component "C4Component" :dynamic "C4Dynamic" "C4Context")
        body
        (case (:level view)
          :container
          (let [cs (filter #(= :container (:el %)) elements)
                others (remove #(= :container (:el %)) elements)]
            (concat (when (:system m)
                      (concat [(str "System_Boundary(boundary__" (mid (:id (:system m))) ", " (q (:name (:system m))) ") {")]
                              (map #(str "  " (el-line % false)) cs) ["}"]))
                    (map #(el-line % false) others)))
          :component
          (let [in (filter #(inside (:id %)) elements)
                out (remove #(inside (:id %)) elements)
                ctx (some #(when (= (:context view) (:id %)) %) (model/elements m))]
            (concat [(str "Boundary(boundary__" (mid (:context view)) ", " (q (or (:name ctx) (name (:context view)))) ", \"bounded context\") {")]
                    (map #(str "  " (el-line % false)) in) ["}"]
                    (map #(el-line % true) out)))
          (map #(el-line % false) elements))]
    (str/join "\n" (concat [(str "%% " (header h model-file view)) kind (str "title " (:description view))]
                           body
                           (for [r rels] (str "Rel(" (mid (:from r)) ", " (mid (:to r)) ", " (q (:description r)) ")"))
                           [""]))))

(defn- spec-models [run]
  (let [cfg (:cfg run)
        decls ((requiring-resolve 'rdm-spec.spec.parser/spec-decls) cfg)]
    (for [d decls]
      {:decl d :views-dir (if (:several? d) (str (:views-dir cfg) "/" (:name d)) (:views-dir cfg))})))

(defn view-files [views-dir view] [(str views-dir "/" (:key view) ".mmd") (str views-dir "/" (:key view) ".svg")])

(defn freshness
  "check's and publish's stage: every view records the model's current hash."
  [run]
  (let [root (:root run)]
    {:findings
     (vec (for [{:keys [decl views-dir]} (spec-models run)
                :let [{m :model} (model/read-file root (:model decl))]
                :when m
                :let [h (model/model-hash m)]
                v (:views m)
                f (view-files views-dir v)
                :let [p (fs/path root f)
                      first-line (when (fs/exists? p) (first (str/split-lines (slurp (str p)))))]
                :when (not (and first-line (str/includes? first-line (str "model-sha256: " h))))]
            (project/finding f "view-stale" (str "the view " (:key v) (if first-line " was generated from another model" " was never generated")
                                                 ": run rdm-spec views (the model's hash is " h ")"))))}))

(defn generate
  "The views task: writes and renders every view of the model."
  [run]
  (let [root (:root run)
        wrote (atom [])
        bad (atom [])]
    (doseq [{:keys [decl views-dir]} (spec-models run)
            :let [{m :model fs* :findings} (model/read-file root (:model decl))]]
      (if-not m (swap! bad into fs*)
      (let [h (model/model-hash m)]
        (fs/create-dirs (fs/path root views-dir))
        (doseq [v (:views m)
                :let [[mmd svg] (view-files views-dir v)
                      src (mermaid m v h (:model decl))]]
          (spit (str (fs/path root mmd)) src)
          (let [tmp (str (fs/path root (str svg ".tmp")))
                r (project/run-cmd ["mmdr" "-i" (str (fs/path root mmd)) "-o" tmp] {:dir root :seconds 120})]
            (when (:not-found? r) (project/cannot-run! "the diagram renderer mmdr is not installed: no view was rendered"))
            (when-not (zero? (or (:exit r) 1))
              (fs/delete-if-exists tmp)
              (project/cannot-run! (str "mmdr could not render " mmd ": " (project/one-line (:err r)))))
            (spit (str (fs/path root svg)) (str "<!-- " (header h (:model decl) v) " -->\n" (slurp tmp)))
            (fs/delete tmp))
          (swap! wrote into [mmd svg])))))
    {:findings @bad :result {:views {:wrote @wrote}}}))
