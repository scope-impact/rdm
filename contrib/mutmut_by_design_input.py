#!/usr/bin/env python3
"""Run mutmut scoped to ONE design input, so survivors are attributable.

`mutmut` starts from the code: it mutates whatever you point it at and reports
which mutants no test killed. That answers "is what's written checked?" — but a
survivor arrives as `rdm.gaps.x_audit_for_gaps__mutmut_17`, which names a
mutant, not a requirement. Nobody can tell from that whether a promise is
unkept.

This wrapper points mutmut at one design input's implementation and one design
input's verifying test, so every survivor belongs to a requirement:

    python contrib/mutmut_by_design_input.py DI-10

Which files implement a design input is not declared anywhere — it is *learned*
from the mutation probes already recorded in its faithfulness verdict. A
reviewer who probed `rdm/gaps.py` to prove a clause has told us, as a side
effect, that `rdm/gaps.py` is where that requirement lives. So the evidence the
probe produced becomes the map this uses.

That has a consequence worth stating plainly: a verdict with no recorded probes
teaches nothing, and this cannot scope to it. Those inputs are listed as
unscopable rather than silently skipped.

GRANULARITY. Scoping is per FILE, not per clause — a probe records the file it
mutated, not the function. So a run for DI-10 mutates all of `rdm/gaps.py`,
including functions belonging to other design inputs, and its survivor list is
an upper bound. DI-10 scoped this way reports 131 survivors against its single
verifying test; most belong to neighbouring requirements with their own tests.
Read the survivor's function name before believing it is yours.

WHAT THIS STILL CANNOT SEE. mutmut mutates code that exists. A clause that was
never implemented produces no mutants, so a requirement can be half-built and
score 100%. Only reading the requirement against the assertions catches that —
`rdm story faithfulness` and a human. This narrows mutmut's blind spot to
absent code; it does not remove it.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
PYPROJECT = REPO / "pyproject.toml"
CONFIG_HEADER = "[tool.mutmut]"


def verdict_for(design_input: str, dhf: Path) -> dict:
    path = dhf / "faithfulness" / f"{design_input}-faithfulness.json"
    if not path.exists():
        sys.exit(f"no verdict for {design_input} at {path}")
    return json.loads(path.read_text())


def implementation_files(verdict: dict) -> list[str]:
    """The files this requirement lives in, learned from its recorded probes."""
    return sorted({p["file"] for p in verdict.get("probes", []) if p.get("file")})


def test_files_for(test_names: list[str]) -> list[str]:
    """Locate the file defining each reviewed test."""
    found: set[str] = set()
    for name in test_names:
        pattern = re.compile(rf"^\s*(async\s+)?def\s+{re.escape(name)}\s*\(", re.M)
        for candidate in (REPO / "tests").rglob("*.py"):
            if pattern.search(candidate.read_text(encoding="utf-8", errors="ignore")):
                found.add(str(candidate.relative_to(REPO)))
                break
    return sorted(found)


def scoped_config(paths: list[str], tests: list[str], existing: str) -> str:
    """Rebuild [tool.mutmut] for this design input, keeping also_copy as-is —
    the data paths the suite needs do not change per requirement."""
    also = re.search(r"^also_copy = \[.*?^\]", existing, re.M | re.S)
    lines = [
        CONFIG_HEADER,
        "# generated by contrib/mutmut_by_design_input.py — restored on exit",
        f"paths_to_mutate = {json.dumps(paths)}",
        f"tests_dir = {json.dumps(tests)}",
    ]
    if also:
        lines.append(also.group(0))
    return "\n".join(lines) + "\n"


def main() -> int:
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    design_input = sys.argv[1]
    dhf = Path(sys.argv[2]) if len(sys.argv) > 2 else REPO / "dhf"

    verdict = verdict_for(design_input, dhf)
    paths = implementation_files(verdict)
    if not paths:
        sys.exit(
            f"{design_input}: no recorded probes, so its implementation files are "
            f"unknown — cannot scope. Record a verdict with --probe first, or pass "
            f"the files by editing [tool.mutmut] directly."
        )
    tests = test_files_for(verdict.get("reviewed_tests", []))
    if not tests:
        sys.exit(f"{design_input}: could not locate its reviewed tests in tests/")

    print(f"{design_input}: mutating {paths}")
    print(f"{design_input}: verified by {tests}")

    original = PYPROJECT.read_text()
    head = original[: original.index(CONFIG_HEADER)] if CONFIG_HEADER in original else original
    try:
        PYPROJECT.write_text(head + scoped_config(paths, tests, original))
        subprocess.run(["mutmut", "run"], cwd=REPO, check=False)
        results = subprocess.run(
            ["mutmut", "results"], cwd=REPO, capture_output=True, text=True
        ).stdout
    finally:
        PYPROJECT.write_text(original)  # always restore

    survivors = [ln.strip() for ln in results.splitlines() if ln.strip().endswith("survived")]
    print(f"\n{design_input}: {len(survivors)} surviving mutant(s)")
    for line in survivors[:20]:
        print(f"  {line}")
    if len(survivors) > 20:
        print(f"  … and {len(survivors) - 20} more")
    print(
        "\nA survivor is a worklist entry, not a defect: decide whether it marks a\n"
        "clause of this requirement that no assertion checks. If it does, strengthen\n"
        "the test, prove it with `rdm story mutation-probe`, and re-record the verdict."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
